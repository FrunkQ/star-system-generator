// webfont request, nothing to load before first paint. Seven rows of `#` and `.` per character,
// drawn as SVG rectangles, so it is crisp at any size on any screen.
//
// COPIED RATHER THAN IMPORTED, on the hub's own advice: the two repositories deploy separately and
// a shared package for one glyph table would buy release coupling and nothing else. The tables are
// pure data with no engine and no hub in them, so they travel in either direction - if this side
// ever adds glyphs, the hub has asked to be told and will take them back.
//
// WHAT WAS NOT TAKEN: everything in the hub's `font.ts` below `fold` paints into a Cloudflare
// Worker's raster and is no use in a browser.
//
// THREE ALPHABETS, and they are genuinely different letters rather than one set with a treatment:
//   GLYPHS  square, two-storey, 5 columns. The readout. Also the only one carrying punctuation
//           and digits - the others fall through to it, which is why a hyphen is a hyphen at any
//           width.
//   ROUND   pointed apexes, circular bowls, single-storey G. A poster face. THE HEADING FACE.
//   NARROW  its own condensed alphabet at 3 columns. A data plate.
//
// TWO TRAPS THE HUB PAID FOR, WORTH KEEPING IN VIEW HERE:
//   - CAPITALS ONLY. There are no lowercase glyphs and adding twenty-six is a project. `fold`
//     enforces it, so every string set in this face is a capitalised one. That suits a wordmark
//     and would fight a sentence.
//   - NARROW MIXES ALPHABETS ON PUNCTUATION. Its letters are 3 columns and the full stop is not
//     defined in it, so `SSE3.1` in NARROW puts a 5-wide stop beside 3-wide letters. That is why
//     the wordmark is set in ROUND.
//
// THE RULE THAT CAME WITH IT, and it is the hub's: **a touch of it, not a theme.** Body text stays
// a system font; the pixels are the trim. The moment every paragraph is a 5x7 bitmap the effect
// stops reading as a choice and starts reading as a broken stylesheet.

