export const GLYPHS = G;
export const GLYPH_H = 7;

export function fold(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/[‘’]/g, "'")
    .replace(/[“”"]/g, '')
    .replace(/[–—]/g, '-')
    .split('')
    .map((ch) => (G[ch] ? ch : ' '))
    .join('')
    .replace(/ {2,}/g, ' ')
    .trim();
}

export interface Run { x: number; y: number; w: number }

/**
 * Every horizontal run of ink in a grid of rows, as rectangles. `.` is blank.
 *
 * This is the only cleverness in the renderer: merging each span into ONE rect means a word is tens
 * of rectangles rather than hundreds.
 */
export function runs(rows: readonly string[]): Run[] {
  const out: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '.') { x++; continue; }
      let w = 1;
      while (x + w < row.length && row[x + w] !== '.') w++;
      out.push({ x, y, w });
      x += w;
    }
  });
  return out;
}

/**
 * A line of text as rows of `#` and `.`, one blank column between glyphs.
 *
 * `family` is the one change from the hub's copy, which is hard-wired to `GLYPHS` because a hub
 * page only ever wanted the base face. Anything the family does not define falls through to the
 * base set - deliberately, so punctuation is punctuation at any width.
 */
export function textRows(text: string, family?: Record<string, string[]>): string[] {
  const rows: string[] = Array.from({ length: GLYPH_H }, () => '');
  for (const ch of fold(text)) {
    const g = family?.[ch] ?? GLYPHS[ch] ?? GLYPHS[' '];
    for (let y = 0; y < GLYPH_H; y++) rows[y] += (rows[y] ? '.' : '') + g[y];
  }
  return rows;
}

/** The width of a grid, in pixels. */
export const gridWidth = (rows: readonly string[]): number => rows.reduce((a, r) => Math.max(a, r.length), 0);

